describe('validatePythonLogMessage: the recorded table', () => {
  it.each(ACCEPTED)('accepts %j (debugpy logged %j)', (message, logged) => {
    expect(SYNTAX_ERROR.test(logged)).toBe(false);
    expect(validatePythonLogMessage(message)).toBeUndefined();
  });

  it.each(LEFT_TO_DEBUGPY)('leaves %j to debugpy (it logged %j)', (message, logged) => {
    expect(logged).toMatch(SYNTAX_ERROR);
    expect(validatePythonLogMessage(message)).toBeUndefined();
  });

  it.each(REFUSED.map((row) => [row.message, row] as const))('refuses %j with the form that works', (_message, row) => {
    expect(row.logged).toMatch(SYNTAX_ERROR);
    expect(validatePythonLogMessage(row.message)).toBe(row.refusal.split('…').join(PREAMBLE));
    for (const [replacement, logged] of row.replacements) {
      if (logged === null) {
        expect(validatePythonLogMessage(replacement)).toBeDefined();
      } else {
        expect(validatePythonLogMessage(replacement)).toBeUndefined();
      }
    }
  });
});

